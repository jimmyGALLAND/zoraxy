func (ar *AuthRouter) listUsers() ([]*User, error) {
	if ar.Database == nil {
		return nil, errors.New("database not available")
	}

	entries, err := ar.Database.ListTable(DB_USERS_TABLE)
	if err != nil {
		return nil, err
	}

	users := []*User{}
	for _, keypairs := range entries {
		if len(keypairs) < 2 {
			continue
		}

		key := string(keypairs[0])
		if !strings.HasPrefix(key, DB_USERS_KEY_PREFIX) {
			continue
		}

		username := strings.TrimPrefix(key, DB_USERS_KEY_PREFIX)
		user, err := ar.getUserByUsername(username)
		if err != nil {
			continue
		}

		users = append(users, user)
	}

	sort.Slice(users, func(i, j int) bool {
		return strings.ToLower(users[i].Username) < strings.ToLower(users[j].Username)
	})

	return users, nil
}

func (ar *AuthRouter) saveUser(user *User, previousUsername string) error {
	if ar.Database == nil {
		return errors.New("database not available")
	}

	if user == nil {
		return errors.New("user is nil")
	}

	user.Username = normalizeUsername(user.Username)
	if user.Username == "" {
		return errors.New("username cannot be empty")
	}

	if strings.Contains(user.Username, "/") || strings.Contains(user.Username, "\\") {
		return errors.New("username contains invalid characters")
	}

	if user.ID == "" {
		user.ID = uuid.NewString()
	}

	if err := ar.Database.Write(DB_USERS_TABLE, ar.userDbKey(user.Username), user); err != nil {
		return err
	}

	if previousUsername != "" && !strings.EqualFold(previousUsername, user.Username) {
		ar.Database.Delete(DB_USERS_TABLE, ar.userDbKey(previousUsername))

		ar.sessionIdStore.Range(func(key, value interface{}) bool {
			name, ok := value.(string)
			if ok && strings.EqualFold(name, previousUsername) {
				ar.sessionIdStore.Store(key, user.Username)
			}
			return true
		})
	}

	return nil
}


// updateUser serializes a complete user read-modify-write operation and always
// applies the mutation to the latest persisted account record.
func (ar *AuthRouter) updateUser(username string, update func(*User) error) (*User, error) {
	if update == nil {
		return nil, errors.New("user update function is nil")
	}

	ar.userMutationMutex.Lock()
	defer ar.userMutationMutex.Unlock()

	user, err := ar.getUserByUsername(username)
	if err != nil {
		return nil, err
	}
	previousUsername := user.Username

	if err := update(user); err != nil {
		return nil, err
	}

	if !strings.EqualFold(previousUsername, user.Username) {
		if _, err := ar.getUserByUsername(user.Username); err == nil {
			return nil, errors.New("new username already exists")
		}
	}

	if err := ar.saveUser(user, previousUsername); err != nil {
		return nil, err
	}
	return user, nil
}

