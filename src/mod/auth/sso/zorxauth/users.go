func isStandardOIDCUserClaim(name string) bool {
	_, ok := standardOIDCUserClaims[name]
	return ok
}

func validateOIDCUserClaimValue(name string, raw json.RawMessage) error {
	if !isStandardOIDCUserClaim(name) {
		return nil
	}
	var value interface{}
	if err := json.Unmarshal(raw, &value); err != nil {
		return errors.New("invalid value for OIDC claim: " + name)
	}
	switch name {
	case "email_verified", "phone_number_verified":
		if _, ok := value.(bool); !ok {
			return errors.New(name + " must be a boolean")
		}
	case "updated_at":
		timestamp, ok := value.(float64)
		if !ok || timestamp < 0 || math.Trunc(timestamp) != timestamp {
			return errors.New("updated_at must be a non-negative integer")
		}
	case "address":
		address, ok := value.(map[string]interface{})
		if !ok {
			return errors.New("address must be an object")
		}
		for _, field := range []string{"formatted", "street_address", "locality", "region", "postal_code", "country"} {
			if fieldValue, exists := address[field]; exists {
				if _, ok := fieldValue.(string); !ok {
					return errors.New("address." + field + " must be a string")
				}
			}
		}
	default:
		if _, ok := value.(string); !ok {
			return errors.New(name + " must be a string")
		}
	}
	return nil
}

